const escapeRegExp = (value) => String(value).replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

const markTarget = (sentence, target) => {
  const plain = String(sentence || "").replace(/<\/?mark>/g, "").trim();
  const normalizedTarget = target === "manage to do" ? "manage" : target.replace(/^be\s+/, "");
  const exact = new RegExp(`\\b${escapeRegExp(normalizedTarget)}\\b`, "i");
  if (exact.test(plain)) return plain.replace(exact, (match) => `<mark>${match}</mark>`);
  const firstWord = normalizedTarget.split(/\s+/)[0];
  const stem = firstWord.replace(/(?:e|y)$/i, "").slice(0, Math.max(4, firstWord.length - 2));
  const inflected = new RegExp(`\\b${escapeRegExp(stem)}[a-z-]*\\b`, "i");
  if (inflected.test(plain)) return plain.replace(inflected, (match) => `<mark>${match}</mark>`);
  return `The passage uses <mark>${target}</mark> in this context: ${plain}`;
};

