import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=await readFile(new URL('../gre-learning/offline-manager.js',import.meta.url),'utf8');
const runSource=source.slice(source.indexOf('async function run(action)'),source.indexOf('\n input.onchange='));
const remoteLine=source.split('\n').find(line=>line.includes('releaseImporter=mountReleaseImporter'));const remoteSource=remoteLine.slice(remoteLine.indexOf('onImport:')+9,-3);
const node=()=>({hidden:false,disabled:false,textContent:'',value:'',classList:{add(){},remove(){}}});
let calls=0;
const context=vm.createContext({controller:null,clearingThisPage:true,AbortController,host:{querySelector:node,querySelectorAll:()=>[]},bookmark:node(),input:node(),cancel:node(),progress:node(),status:node(),modeButton:node(),welcome:{querySelector:node},refresh:async()=>{},chooseVideoMode:async()=>{},downloadReleaseAsset:async()=>{calls++;return new Blob();},importPack:async()=>{calls++;return {wordIds:[1]};},catalog:{},options:()=>({})});
vm.runInContext(runSource+'\n globalThis.remote='+remoteSource,context);
context.action=async()=>{calls++;return {wordIds:[1]};};
await vm.runInContext('run(action)',context);assert.equal(calls,0,'manual shared run must not import during clear');
await assert.rejects(vm.runInContext('remote({})',context));assert.equal(calls,0,'Release must not download during clear');
context.clearingThisPage=false;
await vm.runInContext('run(action)',context);assert.equal(calls,1,'manual import resumes after clear');
await vm.runInContext('remote({})',context);assert.equal(calls,3,'Release download and import resume after clear');
assert.match(source,/isImporting:\(\)=>Boolean\(controller\)\|\|clearingThisPage/);
assert.match(source,/clearingThisPage=true;releaseImporter\?\.refreshCoverage\(\)/);
console.log('PASS clear blocks manual and Release work, disables Release controls, and permits both routes afterward');
