import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=await readFile(new URL('../gre-learning/offline-manager.js',import.meta.url),'utf8');
const downloads=await readFile(new URL('../gre-learning/offline-releases.js',import.meta.url),'utf8');
const runSource=source.slice(source.indexOf('async function run(action)'),source.indexOf('\n input.onchange='));
const node=()=>({hidden:false,disabled:false,textContent:'',value:'',classList:{add(){},remove(){}}});
let calls=0;
const context=vm.createContext({controller:null,clearingThisPage:true,AbortController,CustomEvent:class{},window:{dispatchEvent(){}},refreshDownloads(){},sharedControl:{ticket:async()=>0,state:async()=>({generation:0})},host:{querySelector:node,querySelectorAll:()=>[]},bookmark:node(),input:node(),cancel:node(),progress:node(),status:node(),modeButton:node(),welcome:{querySelector:node},refresh:async()=>{},chooseVideoMode:async()=>{}});
vm.runInContext(runSource,context);
context.action=async()=>{calls++;return {wordIds:[1]};};
await vm.runInContext('run(action)',context);assert.equal(calls,0,'manual import must not run during clear');
context.clearingThisPage=false;context.controller=new AbortController();
await vm.runInContext('run(action)',context);assert.equal(calls,0,'repeat import must not start while a previous import is active');
context.controller=null;
await vm.runInContext('run(action)',context);assert.equal(calls,1,'manual import resumes after clear');
assert.match(source,/clearingThisPage=true/);
assert.match(source,/if\(file\)run\(\(\)=>importPack\(file,catalog,options\(\)\)\)/);
assert.match(source,/mountReleaseDownloads\(\{host,catalog,getReadyIds:\(\)=>savedReadyIds\}\)/);
assert.doesNotMatch(source,/downloadReleaseAsset|onImport:|data-remote/);
assert.doesNotMatch(downloads,/downloadReleaseAsset|onImport|data-remote/);
console.log('PASS clear and active-import guards protect local file import; Release download links have no direct import or ZIP-fetch wiring');
